"""Bundle the default USGS Gazetteer geometries for MoonFOD's curated landmarks."""
from concurrent.futures import ThreadPoolExecutor
from datetime import date
from html import unescape
import json
from pathlib import Path
import re
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parents[1]
CACHE = Path('/tmp/luna-usgs-outline-pages')
CACHE.mkdir(exist_ok=True)
features = re.findall(r"\{id:'([^']+)',name:'([^']+)',gazetteer:'https://planetarynames.wr.usgs.gov/Feature/(\d+)'", (ROOT / 'dist/features.js').read_text())
assert len(features) == 24

def fetch(feature):
    slug, name, feature_id = feature
    url = f'https://planetarynames.wr.usgs.gov/Feature/{feature_id}'
    cached = CACHE / f'{feature_id}.html'
    if not cached.exists():
        request = Request(url, headers={'User-Agent': 'MoonFOD educational lunar atlas; public feature extent import'})
        with urlopen(request, timeout=40) as response:
            cached.write_bytes(response.read())
    page = re.sub(r'<!--.*?-->', '', cached.read_text(), flags=re.S)
    select = re.search(r'<select[^>]*id="selected_control_net"[^>]*>(.*?)</select>', page, re.S).group(1)
    chosen = next(option for option in re.findall(r'<option\b([^>]*)>', select) if re.search(r'\bselected\b', option))
    network_id = re.search(r'value="([^"]+)"', chosen).group(1)
    network = unescape(re.search(r'label="([^"]+)"', chosen).group(1))
    row = re.search(r'<tr class="wkt wkt-' + re.escape(network_id) + r'">(.*?)</tr>', page, re.S).group(1)
    wkt = unescape(re.search(r'<td[^>]*class="wkt_string hidden"[^>]*>(.*?)</td>', row, re.S).group(1)).strip()
    kind = wkt.split('(', 1)[0].strip()
    assert kind in {'POLYGON', 'MULTIPOLYGON', 'LINESTRING', 'MULTILINESTRING'}, (slug, kind)
    paths = []
    for ring in re.findall(r'\(([^()]*)\)', wkt):
        points = []
        for pair in ring.split(','):
            lon, lat = map(float, pair.split())
            assert -90 <= lat <= 90
            points.append([round((lon + 180) % 360 - 180, 5), round(lat, 5)])
        assert len(points) >= 2
        paths.append(points)
    assert paths
    return slug, {'name': name, 'source': url, 'controlNetwork': network, 'geometryType': kind, 'paths': paths}, wkt

with ThreadPoolExecutor(max_workers=4) as pool:
    results = list(pool.map(fetch, features))

data = {slug: entry for slug, entry, _ in results}
(ROOT / 'data').mkdir(exist_ok=True)
(ROOT / 'data/usgs-feature-outlines.json').write_text(json.dumps({
    'retrieved': date.today().isoformat(),
    'note': 'USGS approximate named-feature extents; default control network selected on each feature page.',
    'features': {slug: {**entry, 'wkt': wkt} for slug, entry, wkt in results}
}, indent=2) + '\n')
(ROOT / 'dist/outlines.js').write_text(
    '// USGS Gazetteer approximate feature extents. Longitude/latitude in degrees, east-positive.\n'
    '// Generated by scripts/import-outlines.py; provenance and original WKT are in data/.\n'
    'export const outlines=' + json.dumps(data, separators=(',', ':')) + ';\n')
for slug, entry, _ in results:
    print(f"{slug}: {entry['controlNetwork']}; {entry['geometryType']}; {len(entry['paths'])} paths; {sum(map(len, entry['paths']))} vertices")
print(f"Browser data: {(ROOT / 'dist/outlines.js').stat().st_size:,} bytes")
